import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const sha=text=>crypto.createHash('sha256').update(text).digest('hex');
const bank=JSON.parse(read('checkpoint/bank.json'));
const manifest=JSON.parse(read('checkpoint/release.json'));
assert.equal(bank.version,'exam2-study-checkpoint-1.0.0');
assert.equal(bank.questions.length,261);
assert.equal(sha(read('checkpoint/bank.json')),manifest.bankSha256,'Frozen bank changed');
const preserved=read('.checkpoint-original.html');
assert.equal(sha(preserved),manifest.originalHtmlSha256,'Preserved original HTML changed');
// The preceding original build is validated but not deployed. Publish its exact
// already-live artifact, preserving old code, styles and embedded revisions.
fs.mkdirSync(path.join(root,'dist'),{recursive:true});
fs.writeFileSync(path.join(root,'index.html'),preserved);
fs.writeFileSync(path.join(root,'dist/index.html'),preserved);
assert.equal(sha(read('index.html')),manifest.originalHtmlSha256,'Original quiz HTML changed');
assert.equal(sha(read('data/bank.json')),manifest.originalBankSha256,'Original bank changed');
assert.equal(sha(read('data/legacy-bank-v2.json')),manifest.legacyBankSha256,'Legacy bank changed');
const engine=read('checkpoint/engine.mjs').replace(/^export /gm,'');
const app=read('checkpoint/app.mjs').replace(/^import .*;\n/gm,'');
const js=engine+'\nconst bank='+JSON.stringify(bank).replace(/</g,'\\u003c')+';\n'+app;
new vm.Script(js);
assert(!/\b(?:import|export)\s/.test(js.replace(/\/\/[^\n]*/g,'')) || !/^import |^export /m.test(js));
const css=read('checkpoint/styles.css');
const svg=read('checkpoint/icons/favicon.svg');
const svgUrl='data:image/svg+xml;base64,'+Buffer.from(svg).toString('base64');
const html='<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#09695f"><meta name="description" content="261 reviewed, original NUR2460 Exam 2 questions. Topic-focused study, shuffled choices and detailed rationales. Separate checkpoint progress."><title>NUR2460 · Exam 2 Study Checkpoint</title><link rel="icon" type="image/svg+xml" href="icons/favicon.svg"><link rel="icon" href="icons/favicon.ico" sizes="any"><link rel="apple-touch-icon" href="icons/apple-touch-icon.png"><style>'+css+'</style></head><body><div id="app"></div><noscript>This interactive study checkpoint requires JavaScript. Your original quiz is available at the parent address.</noscript><script>'+js.replace('src="icons/favicon.svg"','src="'+svgUrl+'"').replace(/<\/script/gi,'<\\/script')+'</script></body></html>\n';
for(const pattern of [/\/Users\//,/\.study-build\//,/reviews\/(?:parallel|release)/,/file:\/\//,/gh[opsu]_[A-Za-z0-9]{16}/,/localhost:\d+/]) assert(!pattern.test(html),'Private detail in public HTML: '+pattern);
assert(!/<script[^>]+src=|<link[^>]+rel=["']stylesheet|@import\s/i.test(html),'Unexpected external script or stylesheet');
assert(!/localStorage\.(?:getItem|setItem|removeItem)\(["']nur2460-exam2-v3/.test(html));
const out=path.join(root,'dist/study-checkpoint');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'index.html'),html);
fs.writeFileSync(path.join(out,'release.json'),JSON.stringify({...manifest,htmlSha256:sha(html)},null,2)+'\n');
fs.cpSync(path.join(root,'checkpoint/icons'),path.join(out,'icons'),{recursive:true});
assert.equal(read('index.html'),read('dist/index.html'),'Root release copy changed');
console.log(JSON.stringify({version:bank.version,questions:bank.questions.length,htmlBytes:Buffer.byteLength(html),htmlSha256:sha(html),originalHtmlUnchanged:true,output:'dist/study-checkpoint/index.html'},null,2));
